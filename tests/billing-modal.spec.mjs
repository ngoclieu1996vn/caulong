import {test,expect} from '@playwright/test';
import {openBilling,closeBilling} from './billing-helpers.mjs';
test('billing requires credentials on each opening, closes with Escape and preserves unsaved formatted inputs',async({page})=>{
  await page.goto('detail.html?date=2026-12-22&emulator=1');
  await expect(page.locator('#data-status')).toContainText('Đã đồng bộ');
  await page.getByRole('button',{name:'Tính tiền',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Đăng nhập tính tiền'})).toBeVisible();
  await expect(page.locator('#billing-panel')).toBeHidden();
  await page.getByLabel('Username',{exact:true}).fill('admin');
  await page.getByLabel('Password',{exact:true}).fill('wrong');
  await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
  await expect(page.locator('#billing-login-error')).not.toBeEmpty();
  await expect(page.locator('#billing-panel')).toBeHidden();
  await page.getByLabel('Password',{exact:true}).fill('lieuvippro');
  await page.getByLabel('Password',{exact:true}).press('Enter');
  await expect(page.getByRole('dialog',{name:'Tính tiền buổi cầu'})).toBeVisible();
  await expect(page.getByLabel('Tiền sân (đ)')).toHaveValue('220.000');
  await expect(page.locator('.shuttle-row')).toHaveCount(1);
  await expect(page.getByLabel('Giá cầu 1 (đ)')).toHaveValue('27.000');
  await page.getByLabel('Tiền sân (đ)').fill('230000');
  await expect(page.getByLabel('Tiền sân (đ)')).toHaveValue('230.000');
  await page.keyboard.press('Escape');
  await expect(page.locator('#billing-panel')).toBeHidden();
  await expect(page.locator('#billing-toggle')).toBeFocused();
  await openBilling(page);
  await expect(page.getByLabel('Tiền sân (đ)')).toHaveValue('230.000');
  await closeBilling(page);
  await page.locator('#billing-toggle').click();
  await expect(page.getByLabel('Password',{exact:true})).toHaveValue('lieuvippro');
  await page.keyboard.press('Escape');
  await expect(page.locator('#billing-login')).toBeHidden();
});
test('money inputs format mid-string edits, zero, blank and invalid values; mobile dialog fits',async({page})=>{
  await page.setViewportSize({width:320,height:700});
  await page.goto('detail.html?date=2026-12-23&emulator=1');
  await expect(page.locator('#data-status')).toContainText('Đã đồng bộ');
  await openBilling(page);
  const court=page.getByLabel('Tiền sân (đ)');
  await court.fill('123456');await court.press('Home');await court.press('ArrowRight');await court.press('9');
  await expect(court).toHaveValue('1.923.456');
  expect(await court.evaluate(input=>input.selectionStart)).toBe(3);
  await court.fill('0');await expect(court).toHaveValue('0');
  await court.fill('-100');await expect(page.locator('#billing-summary')).toContainText('số nguyên');
  await court.fill('1.5');await expect(page.locator('#billing-summary')).toContainText('số nguyên');
  await court.fill('220.000');
  await expect(page.getByLabel('Giá mỗi bình (đ)')).toHaveValue('20.000');
  await page.getByRole('button',{name:'+ Thêm loại cầu'}).click();
  await expect(page.locator('.shuttle-row')).toHaveCount(2);
  const box=await page.locator('#billing-panel').boundingBox();
  expect(box.width).toBeLessThanOrEqual(320);expect(box.height).toBeLessThanOrEqual(700);
  expect(await page.locator('#billing-panel').evaluate(dialog=>dialog.scrollWidth<=dialog.clientWidth)).toBe(true);
  await expect(page.locator('#billing-panel').getByRole('button',{name:'Tính tiền',exact:true})).toBeInViewport();
  await page.locator('#billing-panel').screenshot({path:'.playwright/billing-modal-mobile.png'});
  await closeBilling(page);
});
